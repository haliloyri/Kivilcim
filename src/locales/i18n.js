export const getGreeting = (lang) => {
  const hour = new Date().getHours();
  if (hour < 12) return t('goodMorning', lang);
  if (hour < 18) return t('goodAfternoon', lang);
  return t('goodEvening', lang);
};

export const t = (key, lang = 'tr', variables = {}) => {
  // Veritabanı dil kodu vs için esnek yapı
  const value = translations[lang]?.[key] ?? translations.en?.[key] ?? key;
  return Object.entries(variables || {}).reduce(
    (copy, [name, replacement]) => copy.replace(new RegExp(`{{${name}}}`, 'g'), String(replacement)),
    value
  );
};
